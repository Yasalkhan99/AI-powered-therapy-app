// Helper function to get voice for language and gender
export function getVoiceForLanguage(language, gender = 'female') {
  const langKey = language.toLowerCase();
  const voices = ELEVENLABS_VOICES[langKey];
  
  if (!voices) {
    // Fallback to English
    return ELEVENLABS_VOICES.english[gender]?.[0] || ELEVENLABS_VOICES.english.female[0];
  }
  
  return voices[gender]?.[0] || voices.female?.[0] || voices.male?.[0];
}

// Helper function to get all voices for a language
export function getVoicesForLanguage(language) {
  const langKey = language.toLowerCase();
  const voices = ELEVENLABS_VOICES[langKey];
  
  if (!voices) {
    // Fallback to English
    return ELEVENLABS_VOICES.english;
  }
  
  return voices;
}

// Helper function to get available languages
export function getAvailableLanguages() {
  return Object.keys(ELEVENLABS_VOICES).map(lang => ({
    key: lang,
    name: lang.charAt(0).toUpperCase() + lang.slice(1)
  }));
} 